export interface PlanSection { title: string; minutes: number; body: string[] }
export interface LessonPlan {
  lesson: Lesson; scenario: Scenario; minutes: number; grade: string; students: number;
  sections: PlanSection[]; materials: string[];
}

export function buildPlan(lesson: Lesson, minutes: number, grade: string, students: number): LessonPlan {
  const scenario = SCENARIOS.find(s => s.id === lesson.scenarioId) ?? SCENARIOS[0];
  const open = Math.max(3, Math.round(minutes * 0.1));
  const concept = Math.round(minutes * 0.25);
  const practice = Math.round(minutes * 0.2);
  const close = Math.max(3, Math.round(minutes * 0.1));
  const activity = Math.max(5, minutes - open - concept - practice - close);
  const groupSize = students >= 30 ? 6 : 5;
  const groups = Math.max(2, Math.round(students / groupSize));
  const sections: PlanSection[] = [
    { title: 'เปิดบทเรียน', minutes: open, body: [lesson.hook, 'ทบทวนข้อตกลงห้องเรียน 1 ข้อ'] },
    { title: 'สาระสำคัญ', minutes: concept, body: lesson.concepts },
    { title: 'กิจกรรมหลัก', minutes: activity, body: [lesson.activity, `แบ่งกลุ่มประมาณ ${groups} กลุ่ม (กลุ่มละ ${groupSize} คน) สำหรับนักเรียน ${students} คน`] },
    { title: `ฝึกกับสถานการณ์: ${scenario.title}`, minutes: practice, body: [scenario.setup, `D: ${scenario.define}`, ...scenario.respond.map(r => `R: ${r}`)] },
    { title: 'สรุปและประเมิน', minutes: close, body: [...lesson.checks.map(c => `ตัวชี้วัด: ${c}`), `การบ้าน: ${lesson.homework}`] },
  ];
  return {
    lesson, scenario, minutes, grade, students, sections,
    materials: ['กระดานและปากกา', 'การ์ดสถานการณ์ (พิมพ์จากโหมดห้องเรียน)', 'ป้ายสีเขียว/แดง', 'ใบกิจกรรมหรือกระดาษเปล่า', 'ใบประเมินสั้นๆ'],
  };
}

export function planToText(plan: LessonPlan, school: string, teacher: string): string {
  const lines = [
    `📘 แผนการสอน D.A.R.E. บทที่ ${plan.lesson.n}: ${plan.lesson.title}`,
    `🏫 ${school || '(ระบุโรงเรียน)'} | ชั้น ${plan.grade} | นักเรียน ${plan.students} คน | ${plan.minutes} นาที`,
    teacher ? `👮 ผู้สอน: ${teacher}` : '',
    `🎯 จุดเน้น: ${plan.lesson.focus}`, '',
  ];
  let t = 0;
  plan.sections.forEach(s => {
    lines.push(`⏱ ${t}-${t + s.minutes} นาที | ${s.title}`);
    s.body.forEach(b => lines.push(`  • ${b}`));
    t += s.minutes;
  });
  lines.push('', `📩 ข้อความถึงผู้ปกครอง: ${plan.lesson.parentNote}`);
  return lines.filter((l, i, a) => l !== '' || a[i - 1] !== '').join('\n');
}
